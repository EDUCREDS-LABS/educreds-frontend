import { useRef } from "react";
import { QRCodeSVG } from "qrcode.react";
import { Download } from "lucide-react";
import { Button } from "@/components/ui/button";

export interface CredentialShareBadgeData {
  institutionName: string;
  institutionLogo?: string;
  studentName: string;
  credentialTitle: string;
  credentialCategory?: string;
  issuedAt?: string;
  credentialId: string;
  verificationUrl: string;
  blockchainNetwork?: string;
  isMinted?: boolean;
}

function displayDate(value?: string): string {
  if (!value) return "Date not provided";
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? value
    : new Intl.DateTimeFormat(undefined, { day: "numeric", month: "short", year: "numeric" }).format(date);
}

function safeFileName(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48) || "credential";
}

/**
 * Premium personalized credential sharing badge.
 *
 * This is a presentation asset for authenticated students.
 * The QR points to the server-created, expiring sharing URL.
 * Public NFT artwork remains generated by the privacy-safe backend service.
 */
export function CredentialShareBadge({ data }: { data: CredentialShareBadgeData }) {
  const svgRef = useRef<SVGSVGElement>(null);
  const title = data.credentialTitle || "Academic Credential";
  const student = data.studentName || "Credential holder";
  const issuer = data.institutionName || "Issuing institution";
  const category = data.credentialCategory || "ACADEMIC CREDENTIAL";
  const network = data.blockchainNetwork || "BASE NETWORK";
  const awardDate = displayDate(data.issuedAt);

  const downloadSvg = () => {
    const svg = svgRef.current;
    if (!svg) return;
    const clone = svg.cloneNode(true) as SVGSVGElement;
    clone.setAttribute("xmlns", "http://www.w3.org/2000/svg");
    clone.setAttribute("width", "1200");
    clone.setAttribute("height", "1350");
    const source = new XMLSerializer().serializeToString(clone);
    const blob = new Blob([source], { type: "image/svg+xml;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = `${safeFileName(title)}-${safeFileName(student)}-educreds-badge.svg`;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  };

  return (
    <div className="w-full max-w-sm mx-auto space-y-3">
      <svg
        ref={svgRef}
        viewBox="0 0 800 900"
        role="img"
        aria-label={`${title} awarded to ${student} by ${issuer}`}
        className="block w-full h-auto rounded-2xl"
        xmlns="http://www.w3.org/2000/svg"
      >
        <defs>
          <linearGradient id="ec-navy" x1="0" y1="0" x2="1" y2="1">
            <stop offset="0%" stopColor="#082451" />
            <stop offset="100%" stopColor="#001431" />
          </linearGradient>
          <linearGradient id="ec-gold" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0%" stopColor="#FFE28A" />
            <stop offset="50%" stopColor="#E8AD35" />
            <stop offset="100%" stopColor="#BD7C13" />
          </linearGradient>
          <linearGradient id="ec-white" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0%" stopColor="#FFFFFF" />
            <stop offset="100%" stopColor="#F0F5FF" />
          </linearGradient>
          <pattern id="ec-tech-pattern" width="55" height="55" patternUnits="userSpaceOnUse">
            <circle cx="8" cy="8" r="2" fill="#B7CFF6" opacity=".3" />
            <path d="M8 8 L30 30 L50 30" fill="none" stroke="#B7CFF6" strokeWidth="1" opacity=".2" />
          </pattern>
          <clipPath id="ec-inner-clip">
            <path d="M400 65 L695 195 L695 690 L400 850 L105 690 L105 195 Z" />
          </clipPath>
        </defs>

        {/* OUTER BADGE */}
        <path d="M400 12 L755 180 L755 710 L400 888 L45 710 L45 180 Z" fill="url(#ec-navy)" stroke="#D99B29" strokeWidth="5" />
        <path d="M400 42 L725 200 L725 690 L400 850 L75 690 L75 200 Z" fill="url(#ec-gold)" />
        <path d="M400 54 L710 207 L710 680 L400 835 L90 680 L90 207 Z" fill="url(#ec-white)" stroke="#FFFFFF" strokeWidth="4" />

        <g clipPath="url(#ec-inner-clip)">
          <rect x="80" y="55" width="640" height="800" fill="url(#ec-tech-pattern)" />
          <circle cx="650" cy="300" r="95" fill="#DCE9FA" opacity=".2" />
          <circle cx="650" cy="300" r="65" fill="none" stroke="#B8CCEB" opacity=".2" />
        </g>

        {/* EDUCREDS BRANDING */}
        <g transform="translate(400 105)" textAnchor="middle">
          <path d="M-22 -12 L0 -26 L22 -12 L22 12 L0 28 L-22 12 Z" fill="none" stroke="#1554A5" strokeWidth="5" />
          <path d="M-12 0 L-2 10 L16 -12" fill="none" stroke="#1554A5" strokeWidth="5" strokeLinecap="round" strokeLinejoin="round" />
          <text x="0" y="62" fontSize="35" fontWeight="800" fill="#071D43">Edu<tspan fill="#1763BC">Creds</tspan></text>
          <text x="0" y="84" fontSize="11" letterSpacing="3" fill="#10284D">VERIFY • TRUST • EMPOWER</text>
        </g>

        {/* INSTITUTION IDENTITY */}
        <g transform="translate(400 260)">
          {data.institutionLogo ? (
            <image href={data.institutionLogo} x="-300" y="-52" width="104" height="104" preserveAspectRatio="xMidYMid meet" />
          ) : (
            <circle cx="-245" cy="0" r="43" fill="#E4ECF8" stroke="#C4D3E9" />
          )}
          <path d="M-170 -58 V58" stroke="#0B1F43" strokeWidth="2" />
          <text x="-135" y="-2" textLength={Math.min(390, Math.max(150, issuer.length * 15))} lengthAdjust="spacingAndGlyphs" fontSize="29" fontWeight="800" fill="#071B40">
            {issuer}
          </text>
          <text x="-135" y="29" fontSize="14" letterSpacing="4" fill="#18365F">AWARDING INSTITUTION</text>
        </g>

        {/* CREDENTIAL RIBBON */}
        <path d="M20 385 L145 350 L655 350 L780 385 L780 500 L655 530 L145 530 L20 500 Z" fill="url(#ec-navy)" stroke="url(#ec-gold)" strokeWidth="5" />
        <path d="M45 385 L145 360 L655 360 L755 385 L755 490 L655 520 L145 520 L45 490 Z" fill="url(#ec-navy)" />

        {/* Academic emblem */}
        <g transform="translate(120 440)">
          <path d="M-45 -12 L0 -34 L45 -12 L0 12 Z" fill="#F5C653" />
          <path d="M-33 0 V23 L0 40 L33 23 V0" fill="#EAB53F" />
          <path d="M-33 0 L0 17 L33 0" fill="none" stroke="#FFFFFF" strokeWidth="3" />
        </g>

        <text x="455" y="426" textAnchor="middle" textLength={Math.min(520, Math.max(220, title.length * 16))} lengthAdjust="spacingAndGlyphs" fontSize="29" fontWeight="800" fill="#FFFFFF">
          {title}
        </text>
        <text x="455" y="470" textAnchor="middle" textLength={Math.min(440, Math.max(190, category.length * 10))} lengthAdjust="spacingAndGlyphs" fontSize="16" letterSpacing="4" fontWeight="700" fill="#F6CD69">
          {category.toUpperCase()}
        </text>

        {/* RECIPIENT */}
        <g textAnchor="middle">
          <text x="400" y="590" fontSize="17" letterSpacing="5" fill="#162E50">AWARDED TO</text>
          <path d="M150 580 H270" stroke="#152C50" strokeWidth="1.5" />
          <path d="M530 580 H650" stroke="#152C50" strokeWidth="1.5" />
          <text x="400" y="638" textLength={Math.min(520, Math.max(220, student.length * 17))} lengthAdjust="spacingAndGlyphs" fontSize="34" fontWeight="800" fill="#061A3C">
            {student}
          </text>
        </g>

        {/* AWARD INFORMATION */}
        <g textAnchor="middle" fill="#10294E">
          <path d="M280 665 V735" stroke="#9AABC3" strokeWidth="1.5" />
          <path d="M520 665 V735" stroke="#9AABC3" strokeWidth="1.5" />
          <text x="160" y="685" fontSize="15" fontWeight="700">AWARD DATE</text>
          <text x="160" y="713" textLength={Math.min(180, Math.max(90, awardDate.length * 8))} lengthAdjust="spacingAndGlyphs" fontSize="16">{awardDate}</text>
          <text x="400" y="685" fontSize="15" fontWeight="700">INSTITUTION</text>
          <text x="400" y="713" textLength={Math.min(190, Math.max(90, issuer.length * 7))} lengthAdjust="spacingAndGlyphs" fontSize="14">{issuer}</text>
          <text x="640" y="685" fontSize="15" fontWeight="700">CREDENTIAL ID</text>
          <text x="640" y="713" textLength={Math.min(180, Math.max(90, data.credentialId.length * 7))} lengthAdjust="spacingAndGlyphs" fontSize="14">{data.credentialId}</text>
        </g>

        {/* QR and verification details occupy a dedicated band above the footer. */}
        <g transform="translate(300 738)">
          <rect x="-10" y="-10" width="82" height="82" rx="7" fill="#FFFFFF" stroke="#D6E1F1" strokeWidth="2" />
          <QRCodeSVG value={data.verificationUrl} size={66} level="H" bgColor="#FFFFFF" fgColor="#071B3C" />
        </g>

        <g transform="translate(405 754)">
          <path d="M0 -12 L22 -2 V18 Q22 39 0 50 Q-22 39 -22 18 V-2 Z" fill="none" stroke="#1763BC" strokeWidth="4" />
          <path d="M-11 16 L-2 25 L13 7" fill="none" stroke="#1763BC" strokeWidth="4" />
          <text x="34" y="2" fontSize="14" fontWeight="700" fill="#0D2850">SECURE VERIFICATION</text>
          <text x="34" y="25" fontSize="19" fontWeight="800" fill="#1763BC">EduCreds</text>
          <text x="34" y="45" fontSize="11" fill="#0D2850">{data.verificationUrl.replace(/^https?:\/\//, "").slice(0, 38)}</text>
        </g>

        {/* BLOCKCHAIN FOOTER — kept clear of the QR band. */}
        <path d="M285 824 L515 824 L530 875 L400 895 L270 875 Z" fill="url(#ec-navy)" stroke="url(#ec-gold)" strokeWidth="3" />
        <text x="400" y="852" textAnchor="middle" fontSize="14" fontWeight="800" letterSpacing="2" fill="#F6CC68">
          {data.isMinted ? "NFT • BLOCKCHAIN VERIFIED" : "DIGITAL CREDENTIAL"}
        </text>
        <text x="400" y="873" textAnchor="middle" fontSize="11" fill="#FFFFFF">
          POWERED BY EDUCREDS • {network}
        </text>
      </svg>

      <div className="flex items-center justify-between gap-3">
        <p className="text-xs text-muted-foreground">Personalized share artwork · QR links to secure verification</p>
        <Button type="button" variant="outline" size="sm" className="shrink-0 gap-2" onClick={downloadSvg}>
          <Download className="size-4" /> Download SVG
        </Button>
      </div>
    </div>
  );
}
